export async function seedSite(prisma: PrismaClient): Promise<void> {
  console.log('Наполнение сайта...');

  for (const [key, group, ru, kk] of TRANSLATIONS) {
    await prisma.translation.upsert({
      where: { key },
      update: { group },
      create: { key, group, ru, kk },
    });
  }
  console.log(`  переводов: ${TRANSLATIONS.length}`);

  for (const [key, label, value, group] of SETTINGS) {
    await prisma.siteSetting.upsert({
      where: { key },
      update: { label, group },
      create: { key, label, value, group },
    });
  }
  console.log(`  настроек: ${SETTINGS.length}`);

  const categories: Array<[string, string, string, number]> = [
    ['Брусчатка', 'Төсеніш тас', 'bruschatka', 1],
    ['Бордюр', 'Бордюр', 'bordyur', 2],
    ['Дренажные системы', 'Дренаж жүйелері', 'drenazh', 3],
    ['МАФ', 'ШСФ', 'maf', 4],
    ['Натуральный камень', 'Табиғи тас', 'naturalnyy-kamen', 5],
    ['Благоустройство', 'Абаттандыру', 'blagoustroystvo', 6],
  ];

  for (const [name, nameKk, slug, sortOrder] of categories) {
    await prisma.category.upsert({
      where: { slug },
      update: { nameKk, sortOrder },
      create: { name, nameKk, slug, sortOrder },
    });
  }
  console.log(`  категорий: ${categories.length}`);

  const bannerExists = await prisma.banner.count();
  if (bannerExists === 0) {
    await prisma.banner.create({
      data: {
        titleRu: 'Скидка 10% при заказе от 500 м²',
        titleKk: '500 м²-ден тапсырыс бергенде 10% жеңілдік',
        subtitleRu: 'Предложение действует до конца месяца',
        subtitleKk: 'Ұсыныс ай соңына дейін жарамды',
        linkUrl: '/catalog',
        linkTextRu: 'Смотреть каталог',
        linkTextKk: 'Каталогты қарау',
      },
    });
    console.log('  баннер: создан');
  }
}
